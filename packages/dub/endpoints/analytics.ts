import type { DubEndpoints } from '..';
import { call } from './call';
import {
	DubEndpointInputSchemas as Inputs,
	DubEndpointOutputSchemas as Outputs,
} from './types';

export const retrieve: DubEndpoints['analyticsRetrieve'] = (ctx, input) =>
	call(
		ctx,
		{
			event: 'analytics.retrieve',
			input: Inputs.analyticsRetrieve,
			output: Outputs.analyticsRetrieve,
		},
		input,
		({
			event,
			groupBy,
			domain,
			key,
			linkId,
			externalId,
			tenantId,
			tagId,
			folderId,
			partnerTagId,
			groupId,
			partnerId,
			customerId,
			interval,
			start,
			end,
			timezone,
			country,
			city,
			region,
			continent,
			device,
			browser,
			os,
			trigger,
			eventName,
			referer,
			refererUrl,
			url,
			utm_source,
			utm_medium,
			utm_campaign,
			utm_term,
			utm_content,
			root,
			saleType,
			query,
		}) => ({
			method: 'GET',
			path: '/analytics',
			query: {
				event,
				groupBy,
				domain,
				key,
				linkId,
				externalId,
				tenantId,
				tagId,
				folderId,
				partnerTagId,
				groupId,
				partnerId,
				customerId,
				interval,
				start,
				end,
				timezone,
				country,
				city,
				region,
				continent,
				device,
				browser,
				os,
				trigger,
				eventName,
				referer,
				refererUrl,
				url,
				utm_source,
				utm_medium,
				utm_campaign,
				utm_term,
				utm_content,
				root,
				saleType,
				query,
			},
		}),
		{
			log: ({ event, groupBy }) => ({
				event: event ?? 'clicks',
				groupBy: groupBy ?? 'count',
			}),
		},
	);
