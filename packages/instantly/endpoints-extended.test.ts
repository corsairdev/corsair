let fetchMock: jest.SpyInstance;

// unknown: response bodies are arbitrary JSON or CSV text.
function respond(body: unknown, status = 200, csv = false) {
	fetchMock.mockResolvedValueOnce(
		new Response(csv ? String(body) : JSON.stringify(body), {
			status,
			headers: { 'Content-Type': csv ? 'text/csv' : 'application/json' },
		}),
	);
}

function lastRequest() {
	const [url, init] = fetchMock.mock.calls.at(-1) as [string, RequestInit];
	const parsed = new URL(url);
	return {
		path: parsed.pathname,
		query: Object.fromEntries(parsed.searchParams),
		method: init.method,
		headers: new Headers(init.headers),
		// unknown: the request body is whatever the endpoint serialized.
		body: init.body ? (JSON.parse(String(init.body)) as unknown) : null,
	};
}

beforeEach(() => {
	fetchMock = jest.spyOn(globalThis, 'fetch');
	mockLog.mockClear();
});

afterEach(() => {
	jest.restoreAllMocks();
});

describe('the rest of Instantly API v2', () => {
	it('covers every added operation once', () => {
		expect(new Set(cases.map((c) => c.operation)).size).toBe(127);
	});

	it.each(cases)(
		'$operation sends $method $path',
		async ({
			operation,
			endpoint,
			input,
			response,
			method,
			path,
			query,
			body,
			csv,
		}) => {
			respond(response, 200, csv);

			// The fake context only carries what the endpoints read (ctx.key).
			const result = await endpoint({ key: API_KEY } as never, input as never);

			const sent = lastRequest();
			expect(sent.method).toBe(method);
			expect(sent.path).toBe(path);
			expect(sent.headers.get('authorization')).toBe(`Bearer ${API_KEY}`);
			expect(sent.query).toEqual(query);
			expect(sent.body).toEqual(body);
			expect(result).toEqual(response);
			expect(mockLog).toHaveBeenCalledWith(
				expect.anything(),
				`instantly.${operation}`,
				expect.any(Object),
				'completed',
			);
		},
	);

	it.each(cases.filter((c) => c.write))(
		'$operation is sent once, even after a 429',
		async ({ endpoint, input }) => {
			respond(
				{ statusCode: 429, error: 'Too Many Requests', message: 'slow down' },
				429,
			);

			await expect(
				endpoint({ key: API_KEY } as never, input as never),
			).rejects.toMatchObject({ status: 429 });
			expect(fetchMock).toHaveBeenCalledTimes(1);
		},
	);
});
