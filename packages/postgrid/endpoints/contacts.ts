import type { PostgridEndpoints } from '..';
import { segment } from '../client';
import { call } from './call';
import {
	PostgridEndpointInputSchemas as Inputs,
	PostgridEndpointOutputSchemas as Outputs,
} from './types';

export const list: PostgridEndpoints['contactsList'] = (ctx, input) =>
	call(
		ctx,
		{
			event: 'contacts.list',
			input: Inputs.contactsList,
			output: Outputs.contactsList,
		},
		input,
		({ skip, limit, search }) => ({
			method: 'GET',
			path: '/contacts',
			query: { skip, limit, search },
		}),
		{ log: (_, result) => ({ count: result.data.length }) },
	);

export const get: PostgridEndpoints['contactsGet'] = (ctx, input) =>
	call(
		ctx,
		{
			event: 'contacts.get',
			input: Inputs.contactsGet,
			output: Outputs.contactsGet,
		},
		input,
		({ id }) => ({ method: 'GET', path: `/contacts/${segment(id)}` }),
		{ log: ({ id }) => ({ contactId: id }) },
	);

export const create: PostgridEndpoints['contactsCreate'] = (ctx, input) =>
	call(
		ctx,
		{
			event: 'contacts.create',
			input: Inputs.contactsCreate,
			output: Outputs.contactsCreate,
		},
		input,
		(body) => ({ method: 'POST', path: '/contacts', body }),
		{ log: (_, result) => ({ contactId: result.id ?? undefined }) },
	);

export const remove: PostgridEndpoints['contactsDelete'] = (ctx, input) =>
	call(
		ctx,
		{
			event: 'contacts.delete',
			input: Inputs.contactsDelete,
			output: Outputs.contactsDelete,
		},
		input,
		({ id }) => ({ method: 'DELETE', path: `/contacts/${segment(id)}` }),
		{ log: ({ id }) => ({ contactId: id }) },
	);
