import { z } from 'zod';

export type FireberryJsonValue =
	| string
	| number
	| boolean
	| null
	| FireberryJsonValue[]
	| { [key: string]: FireberryJsonValue };
let fireberryJsonValueSchema: z.ZodType<FireberryJsonValue>;
fireberryJsonValueSchema = z.lazy(() =>
	z.union([
		z.string(),
		z.number(),
		z.boolean(),
		z.null(),
		z.array(fireberryJsonValueSchema),
		z.record(z.string(), fireberryJsonValueSchema),
	]),
);
export const FireberryJsonValueSchema = fireberryJsonValueSchema;

function fireberryRecordSchema(shape: Record<string, z.ZodType>) {
	const declaredFields = new Set(Object.keys(shape));
	return z
		.object(shape)
		.catchall(FireberryJsonValueSchema)
		.superRefine((value, ctx) => {
			for (const fieldName of Object.keys(value)) {
				if (!declaredFields.has(fieldName) && !fieldName.startsWith('pcf')) {
					ctx.addIssue({
						code: 'custom',
						path: [fieldName],
						message:
							'Unknown field; custom Fireberry fields use the pcf prefix.',
					});
				}
			}
		});
}
// The REST update (PUT) accepts partial bodies: a live account update without accountname
// succeeded, so update schemas keep field types but do not require the reference's create fields.
function fireberryUpdateRecordSchema(shape: Record<string, z.ZodType>) {
	return fireberryRecordSchema(
		Object.fromEntries(
			Object.entries(shape).map(([fieldName, schema]) => [
				fieldName,
				schema.optional(),
			]),
		),
	);
}
