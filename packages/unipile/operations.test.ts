let fetchMock: jest.SpyInstance;

beforeEach(() => {
	fetchMock = jest.spyOn(globalThis, 'fetch');
	mockLog.mockClear();
});

afterEach(() => {
	fetchMock.mockRestore();
});

function lastRequest() {
	const [url, init] = fetchMock.mock.calls.at(-1) as [string, RequestInit];
	const parsed = new URL(url);
	const query: Record<string, string | string[]> = {};
	for (const key of new Set(parsed.searchParams.keys())) {
		const values = parsed.searchParams.getAll(key);
		query[key] = values.length > 1 ? values : (values[0] ?? '');
	}
	return {
		path: url.slice(parsed.origin.length).split('?')[0],
		query,
		method: init.method,
		headers: new Headers(init.headers),
		// unknown: whatever the endpoint serialized.
		body: init.body ? (JSON.parse(String(init.body)) as unknown) : null,
	};
}

describe('Unipile generated operations', () => {
	it('covers 115 operations', () => {
		expect(new Set(cases.map((c) => c.operation)).size).toBe(115);
	});

	it.each(cases)('$operation sends its documented request', async (c) => {
		fetchMock.mockResolvedValueOnce(
			c.status === 204
				? new Response(null, { status: 204 })
				: new Response(JSON.stringify(c.response), {
						status: c.status,
						headers: { 'Content-Type': 'application/json' },
					}),
		);

		// The fake context only carries what endpoints read (ctx.key).
		const result = await c.endpoint(
			{ key: 'uk-test' } as never,
			c.input as never,
		);

		const sent = lastRequest();
		expect(sent.method).toBe(c.method);
		expect(sent.path).toBe(c.path);
		expect(sent.headers.get('x-api-key')).toBe('uk-test');
		for (const [key, value] of Object.entries(c.query)) {
			expect(sent.query[key]).toEqual(value);
		}
		if (c.body === null) {
			expect(
				sent.body === null || Object.keys(sent.body as object).length === 0,
			).toBe(true);
		} else {
			expect(sent.body).toMatchObject(c.body as object);
		}
		// The spec's minimal response parses: no parse_warning on writes.
		expect(result).not.toHaveProperty('parse_warning');
		if (c.status === 204) expect(result).toEqual({ success: true });
		expect(mockLog).toHaveBeenCalledWith(
			expect.anything(),
			`unipile.${c.operation}`,
			expect.any(Object),
			'completed',
		);
	});
});
