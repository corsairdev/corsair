import type { CorsairEndpoint } from 'corsair/core';
import { logEventFromContext } from 'corsair/core';
import type { z } from 'zod';
import type { GetProspectContext } from '..';
import { makeGetProspectRequest } from '../client';
import type { GetProspectOperationDefinition } from './types';
import {
	GetProspectOperationInputSchemas,
	GetProspectOperationOutputSchemas,
	getProspectOperationDefinitions,
} from './types';

function createEndpoint<
	InputSchema extends z.ZodType,
	OutputSchema extends z.ZodType,
>(
	id: string,
	inputSchema: InputSchema,
	outputSchema: OutputSchema,
	definition: GetProspectOperationDefinition,
	readPath: (input: z.output<InputSchema>) => object | undefined,
	// Per-operation query values differ; the input schema validates them before they are forwarded.
	readQuery: (
		input: z.output<InputSchema>,
	) => Record<string, unknown> | undefined,
	readHeaders: (
		input: z.output<InputSchema>,
	) => { idempotencyKey?: string } | undefined,
	readBody: (input: z.output<InputSchema>) => object | undefined,
): CorsairEndpoint<
	GetProspectContext,
	z.input<InputSchema>,
	z.output<OutputSchema>
> {
	return async (ctx, input) => {
		const parsedInput = inputSchema.parse(input);
		const inputPath = readPath(parsedInput);
		let url: string = definition.path;
		for (const name of definition.pathParams) {
			// Path values are untrusted input until the operation schema has parsed them.
			const value = Object.entries(inputPath ?? {}).find(
				([key]) => key === name,
			)?.[1];
			if (typeof value !== 'string')
				throw new Error('Missing validated path parameter');
			url = url.replace(`{${name}}`, encodeURIComponent(value));
		}
		const inputQuery = readQuery(parsedInput);
		const query = inputQuery
			? Object.fromEntries(
					Object.entries(inputQuery).filter(([, value]) => value !== undefined),
				)
			: undefined;
		const inputHeaders = readHeaders(parsedInput);
		const headers = inputHeaders?.idempotencyKey
			? { 'Idempotency-Key': inputHeaders.idempotencyKey }
			: undefined;
		const body = readBody(parsedInput);
		// The transport response is untrusted until the operation-specific OpenAPI-derived schema validates it.
		const response: unknown = await makeGetProspectRequest<unknown>(
			url,
			ctx.key,
			{
				method: definition.method,
				body,
				query,
				headers,
				timeout: definition.timeout,
			},
		);
		const parsed = outputSchema.parse(response);
		await logEventFromContext(
			ctx,
			`getprospect.${id}`,
			{ operation: id },
			'completed',
		);
		return parsed;
	};
}

